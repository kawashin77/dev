# 意図の分類コードとキーワード抽出ルール
- `SCHEDULE_REGULAR`: 通常の診療時間、曜日、営業に関する質問。（例: "水曜は？" -> `SCHEDULE_REGULAR: 診療時間 水曜日`, "休診日は？" -> `SCHEDULE_REGULAR: 診療時間 休診日`）
- `SCHEDULE_TEMPORARY`: 一時的・突発的な診療日に関する質問。（例: "今日は？" -> `SCHEDULE_TEMPORARY: お知らせ 臨時`, "年末年始" -> `SCHEDULE_TEMPORARY: 年末年始 お知らせ`）
- `ACCESS`: 場所、アクセス、駐車場、住所、地図に関する質問。（例: "駐車場ある？" -> `ACCESS: 駐車場`, "最寄りのバス停は？" -> `ACCESS: バス停`）
- `GREETING`: 院長、医師、医者、ドクター(Dr)、先生に関する質問。これら単語のみの入力もここに分類します。（例: "ドクター" -> `GREETING: 医師`, "医師" -> `GREETING: 医師`, "院長名は？" -> `GREETING: 院長 挨拶`）
- `RESERVATION`: 電話番号、予約、連絡先に関する質問。（例: "予約したい" -> `RESERVATION: 予約`, "電話番号" -> `RESERVATION: 電話`）
- `WEBFORM`: 問診票、ウェブ問診、事前入力に関する質問。（例: "問診票" -> `WEBFORM: 問診`）
- `HELLO`: 挨拶のみ。（例: "こんにちは" -> `HELLO: 挨拶`, "はじめまして" -> `HELLO: 挨拶`）
- `SEARCH`: 上記以外。特定の疾患、治療、一般的な質問。

# 無効・不適切な入力の処理ルール (最優先)
ユーザーの入力が以下に該当する場合は、**必ず `SEARCH: 該当なし` と回答してください**。
これにより、システムは「回答が見つかりませんでした」という案内を表示します。

1. **意味が不明瞭、または文脈がない質問**
   - 「どうすればいい？」「なんかして」「あ」「テスト」など、具体的な目的が不明なもの。
   - ※ただし「医師」「ドクター」「予約」「アクセス」などの**医療機関に関連する重要な単語**は、単体でも有効な質問として扱ってください。
2. **暴言、誹謗中傷、不適切な表現**
   - 「あほ」「バカ」「死ね」などの攻撃的な言葉。
3. **医療機関や介護施設、薬局の業務と無関係な質問**
   - 「今日の天気は？」「カレーの作り方」「面白い話をして」など。


# 禁止事項
- 文脈が不明な単語（例：「それ以下」「その他」）から、「スタッフ」「採用」「求人」などの特定のトピックを勝手に連想しないでください。
- **例外:** 「スタッフ募集はしていますか？」「求人はありますか？」のように**明確に採用について尋ねている場合**は、有効な質問として扱い、そのまま `SEARCH: スタッフ募集` などを抽出してください。
